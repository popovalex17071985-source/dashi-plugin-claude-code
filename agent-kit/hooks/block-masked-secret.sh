#!/usr/bin/env bash
# PreToolUse → Bash / Write / Edit. Exit 2 blocks the call.
#
# Секрет никогда не записывается в файл в замаскированном виде. Канал режет
# любой токен длиннее 24 знаков на выходе в чат («8ad1***0bd4»), и агент,
# который берёт значение из переписки, а не из первоисточника, кладёт на диск
# маску. Дальше всё выглядит рабочим -- файл есть, служба поднялась -- а любой
# запрос отвечает 401, и агент часами ищет несуществующую песочницу
# (живой агент 08.09.2026).
set -euo pipefail
input="$(cat)"
payload="$(printf '%s' "$input" | jq -r '
  (.tool_input.command // "") + "\n" +
  (.tool_input.content // "") + "\n" +
  (.tool_input.new_string // "")')"

# 4 знака + звёздочки + 4 знака -- сигнатура редактора секретов.
if printf '%s' "$payload" | grep -qE '[A-Za-z0-9_]{4}\*{2,}[A-Za-z0-9_]{4}'; then
  echo "Это замаскированное значение, а не секрет: канал режет длинные токены" >&2
  echo "на выходе в чат. Возьми ключ из первоисточника (личный кабинет, файл" >&2
  echo "секретов, менеджер паролей), не из переписки со мной." >&2
  exit 2
fi
exit 0
