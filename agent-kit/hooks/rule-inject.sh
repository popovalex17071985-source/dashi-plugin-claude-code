#!/usr/bin/env bash
# rule-inject.sh -- UserPromptSubmit: правило под тему хода, ровно когда оно нужно.
#
# Писаных правил у агента десятки, а держатся единицы: прочитано на старте
# сессии -- к пятому ходу растворилось. Работает только реактивная подача: тема
# хода -> одно-два правила по ней. На нейтральном ходу молчит и стоит ноль
# токенов. (Механизм выстрадан Jarvis'ом 10.08.2026, перенесён всем 11.09.2026.)
set -euo pipefail

CLAUDE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INPUT=$(cat)
PROMPT=$(echo "$INPUT" | jq -r '.user_message // .prompt // ""' 2>/dev/null || echo "")
[[ -z "$PROMPT" ]] && exit 0

emit() { echo "[ПРАВИЛО ПО ТЕМЕ ХОДА] $1"; }
match() { echo "$PROMPT" | grep -qiE "$1"; }

# Пояс хозяина кладёт install-kit.sh; без файла про время молчим, чем врать.
TZ_OWNER="$(cat "$CLAUDE_DIR/core/owner-tz" 2>/dev/null || true)"

# 1. Цифры и отчёты -> первоисточник, а не соседний файл и не память.
match "сколько|отчёт|отчет|посчитай|сводк|остат|выручк|продано|итог" &&
  emit "Цифры -- только из первоисточника: открой сам файл, базу или API и посчитай по нему. Соседний отчёт, память и чужая выжимка -- не источник. Не уверен -- скажи «проверяю», а не называй число."

# 2. Время -> пояс хозяина, конвертация ДО записи.
[[ -n "$TZ_OWNER" ]] && match "напомн|во сколько|в [0-9]{1,2}[: ]|утра|вечера|завтра|расписан|крон" &&
  emit "Время говорим и пишем в поясе хозяина ($TZ_OWNER). Сервер может жить в другом -- переводи ПЕРЕД тем как назвать час или поставить задачу по расписанию, а не после."

# 3. Удаление и замена -> сначала бэкап и поиск всех форм имени.
match "удали|снеси|переименуй|очист|замен(и|ить)|drop |rm |перезапиш" &&
  emit "Перед удалением или переименованием: бэкап, потом поиск ВСЕХ форм имени (в коде, в конфигах, в строках). Запись через PATCH/PUT -- это полная замена: сначала прочитать, изменить, записать, потом перечитать и убедиться."

# 4. Долгий прогон -> он должен отчитаться сам.
match "скрейп|прогон|запусти|пересчита|синхрониз|импорт|выгруз" &&
  emit "Долгую работу запускай так, чтобы отчёт был привязан к самой команде -- иначе она закончится, а хозяин узнает об этом, только когда спросит. Самодельные ждуны на pgrep матчат сами себя и висят вечно."

# 5. «Почему не работает» -> диагноз из логов, а не из головы.
match "почему|не работает|сломал|ошибк|баг|не пришл|не отправ|завис" &&
  emit "Диагноз -- из логов и кода, а не из предположения. Первый отказ источника = одна проверенная гипотеза, не вывод: перебери несколько путей, прежде чем сказать «не могу»."

exit 0
