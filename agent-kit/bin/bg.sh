#!/usr/bin/env bash
# Долгий прогон в фоне, который САМ доложит оператору результат.
#
# Зачем ещё одна обёртка поверх run-and-report.sh: я запускаю долгие вещи через
# `nohup ... &` и рядом ставлю «ждуна» (until pgrep/grep — сплю — проверяю).
# Ждун ломается тихо: `pgrep -f x` матчит собственную командную строку и висит
# вечно, и оператор узнаёт о готовой работе, только когда пнёт (10.08.2026 — прогон
# оборота лежал готовым 25 минут, «как ты меня заебал»). Гейт-хук на pgrep есть,
# но к фоновым Bash-вызовам PreToolUse не применяется — проверено, дыра реальна.
#
# Здесь ждун не нужен в принципе: отчёт привязан к самой команде.
# Успех и падение уходят в личку, третьего состояния «тишина» нет.
#
#   bin/bg.sh "пересчёт оборота" bin/gincore/update_oborot.sh
#   TAIL=15 bin/bg.sh "скрейп аксов" python3 bin/gincore/sale-metrics-report.py
#
# Печатает pid и путь к логу: за состоянием следить по `kill -0 <pid>` и росту
# лога, НЕ по имени процесса в ps.
set -euo pipefail

ROOT=__WORKSPACE__
TITLE="${1:?нужно описание задачи}"
shift
[ "$#" -gt 0 ] || { echo "нужна команда" >&2; exit 2; }

# Команда передаётся АРГУМЕНТАМИ, не одной строкой: `bg.sh "текст" ssh host "cmd"`,
# а не `bg.sh "текст" "ssh host \'cmd\'"`. Со строкой обёртка искала бы файл с
# таким именем, умирала за секунду, и прогон «шёл» только в моей голове
# (11.09.2026, полчаса тишины на переустановке агента).
command -v "$1" >/dev/null 2>&1 || [ -x "$1" ] || {
  echo "bg.sh: «$1» — не команда. Передавай аргументами: bg.sh \"описание\" ssh -i key host \"cmd\"" >&2
  exit 2
}

BG_JOB_ID="bg-$$-$(date +%s)"
export BG_JOB_ID
LOG=$(mktemp /tmp/bg-XXXXXX.log)
setsid nohup "$ROOT/bin/run-and-report.sh" "$TITLE" "$@" >"$LOG" 2>&1 &
PID=$!
echo "pid=$PID log=$LOG"
# Ранняя проверка: задача, умершая в первые секунды (кривой запуск, нет прав,
# сразу упало), раньше выглядела как «идёт». Через 8 секунд смотрим: процесс
# жив -- молчим; в реестре есть отметка о финише -- задача просто успела
# отработать, тоже молчим; ни того, ни другого -- значит умерла, сообщаем.
( sleep 8
  kill -0 "$PID" 2>/dev/null && exit 0
  grep -q "\"$BG_JOB_ID\".*done" "$ROOT/data/jobs.jsonl" 2>/dev/null && exit 0
  grep -q '"id": "'"$BG_JOB_ID"'", "done"' "$ROOT/data/jobs.jsonl" 2>/dev/null && exit 0
  TAIL_TXT=$(tail -n 3 "$LOG" 2>/dev/null | cut -c1-300)
  python3 "$ROOT/bin/tg-send.py" "Задача «$TITLE» не запустилась -- умерла в первые секунды.

$TAIL_TXT

Разбираюсь." >/dev/null 2>&1 || true
) >/dev/null 2>&1 &

echo "отчёт придёт в личку сам; следить: kill -0 $PID; tail $LOG"
