#!/usr/bin/env bash
# Утренняя самопроверка агента: хуки, крон, канарейка планировщика, модель,
# ссылки памяти. Хозяину уходят ТОЛЬКО подозрения — тишина значит «всё зелено».
#
# Зачем: агент умеет молча перестать работать. 27.08.2026 у боевого агента крон
# шесть часов не выполнял задачи (лишняя жёсткая ссылка на файле расписания) —
# встали все ночные задачи разом, и хозяин узнал об этом сам, случайно.
# Самопроверка — единственное место, где такое всплывает без человека.
set -euo pipefail
WORKSPACE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$WORKSPACE"
mkdir -p logs
OUT=$(/usr/bin/python3 bin/self-audit.py --human 2>/dev/null | head -c 3500 || true)
if [ -n "${DRY:-}" ]; then printf '%s\n' "$OUT"; exit 0; fi
[ -n "$OUT" ] || exit 0
# Список — и в лог тоже: хозяин спросит «что там было», а в логе одна отметка
# «отправлено» — проверять нечего.
printf '[%s]\n%s\n' "$(date -Iseconds)" "$OUT" >> logs/self-audit.log
/usr/bin/python3 "$WORKSPACE/bin/tg-send.py" "$OUT"
